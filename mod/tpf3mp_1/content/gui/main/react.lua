local function enqueueParallel(name, useFnParams, join)
	local future = api.gui.react.enqueueParallelWorkItem(name, useFnParams)
	local function joinFn()
		if join then
			local parallelResult = future:get()
			join(parallelResult, useFnParams)
		end
	end
	enqueueJoin(joinFn, name)
end

