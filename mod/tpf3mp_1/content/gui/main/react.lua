local function useAction(rendererComponentRef, action, key2)
	assert(callingRecipeCtx ~= nil)
	local selfRef = callingRecipeCtx:declareSelfRef()
	local rcRef = useRef(rendererComponentRef)
	local actionRef = useRef(action)

	local function unbind() -- remove binding from the RC it was associated to (if any)
		local oldRef = rcRef:get() and rcRef:get():get()
		if oldRef then
			local oldApi = oldRef:getIdentity() and oldRef:getApi() or nil
			if oldApi then
				-- onMount already called and either action or rc changed
				oldApi.unbindAction(selfRef)
			end
		end
		actionRef:set(nil)
	end

	-- if RC or action changes, remove old action from old rc
	if action ~= actionRef:get() or rendererComponentRef:getUnderlyingStatePtr() ~= rcRef:get():getUnderlyingStatePtr() then
		unbind()
	end

	-- on unmount, always unbind from old RC
	callingRecipeCtx:onUnmount(function()
		unbind()
	end)

	-- try to bind new action:
	local newApi = rendererComponentRef:get() and rendererComponentRef:get():getIdentity() and rendererComponentRef:get():getApi()
	if newApi and selfRef:get() then
		-- if self and target already exists, we can't do it in onMount() but luckily in this case we can call the API directly
		newApi.bindAction(selfRef, action, key2)
		rcRef:set(rendererComponentRef)
		actionRef:set(action)
	else
		-- self or target doesn't exist yet
		callingRecipeCtx:onMount(function()
			local rcApi = rendererComponentRef:get() and rendererComponentRef:get():getIdentity() and rendererComponentRef:get():getApi() or nil
			if rcApi then
				rcRef:set(rendererComponentRef)
				rcApi.bindAction(selfRef, action, key2)
				actionRef:set(action)
			end
		end)
	end

	return selfRef -- this is required to call rendererComponentApi.setActiveOwner()
end

