local function collectMeta(withUserdata, isLayoutChild, packed, recipeId, recipeName)
	if packed[1] == nil then return nil end
	if type(packed[1]) ~= "table" then return nil end
	local meta = packed[1].meta
	if meta ~= nil and isLayoutChild then
		debugPrint(meta)
		local message = "LayoutChild nodes do not support the 'meta' attribute"
		message = (message .. "\n (used together with recipeId = " .. tostring(recipeId) .. " aka '" .. tostring(recipeName) .. ")\n")
		assert(false, message)
		return nil
	end
	return meta
end

local function stripMeta(packed)
	-- strip 'meta' from packed[1]
	local noMeta = {}
	for k, v in ipairs(packed) do
		if k == 1 then
			noMeta[1] = {}
			for key, value in pairs(packed[1]) do
				if key ~= "meta" then
					noMeta[1][key] = value
				end
			end
		else
			noMeta[k] = packed[k]
		end
	end
	return noMeta
end

-- context used for react hooks (only valid during recipe function)
local callingRecipeCtx = nil

local function RegisterRecipeInner(recipeId, name, fn, withUserdata, isLayoutChild, wrappedRecipeFn)
	local innerRecipeId = nil
	if wrappedRecipeFn then
		innerRecipeId = recipeFnToRecipeId[wrappedRecipeFn]
	end
	log.verbose("RegisterRecipeInner(" .. tostring(recipeId) .. ", " .. name .. ")" .. (wrappedRecipeFn and (" as wrapper around " .. tostring(innerRecipeId)) or ""))

	local myRecipeCtx = nil

	-- consider: instead of pack + unpack, use an std::vector in the backend

	if innerRecipeId then
		_react.recipeMetas[recipeId] = { innerRecipeId = innerRecipeId }
	end
	_react.recipes[recipeId] = function(ctx, cppProps)
		local ctxBackup = callingRecipeCtx
		callingRecipeCtx = ctx

		local props = cppProps and cppProps.props
		--local style = cppProps and cppProps.style
		--local layout = cppProps and cppProps.layout

		local result = nil
		if props ~= nil then
			result = fn(table.unpack(props))
		else
			result = fn()
		end
		callingRecipeCtx = ctxBackup
		if (type(result) ~= "nil" and type(result) ~= "table") then
			result = { result }
		end
		if innerRecipeId then
			if result[1] then
				if not ctx:checkRecipeMatch(result[1], innerRecipeId, true) then
					log.verbose(" (happened inside wrapper recipe recipeId = "..tostring(recipeId)..", name = "..name)
				elseif #result ~= 1 then
					local str = string_util.format(
						"Wrapper recipe returned {num} children (must be 0 or 1). RecipeId = {id}, name = {name}.", {
							num = tostring(#result),
							id = tostring(recipeId),
							name = name,
						})
					error(str)
				end
			end
		end
		-- Note: result == nil means context's children,
		--       (implying 'no children', unless appendChildToResult() has been used)
		ctx:setResult(result)
	end

	local resultOriginal = function(...)
		assert(callingRecipeCtx ~= nil)

		local style, ref, packed = splitParams(...)

		local localKey = nil
		local discardNodeIdentity = nil

		local meta = collectMeta(withUserdata, isLayoutChild, packed, recipeId, name)
		if meta and meta.class ~= nil then
			if style then
				log.warning("meta={class={"..tostring(meta.class) .."}} overrides react.style{class="..tostring(style.class).."}")
			end
			style = { class = meta.class }
		end
		if meta and not withUserdata then
			packed = stripMeta(packed)
		end

		if meta and meta.localKey then
			localKey = meta.localKey
			discardNodeIdentity = meta.discardNodeIdentity
			if next(meta) == nil then
				meta = nil
			end
		end

		if withUserdata then
			packed[1] = makeUserdata(name, packed[1]) -- note: this strips 'meta'
			if isLayoutChild then
				localKey = packed[1].localKey or nil
			end
		end

		--
		--
		--print("style: ")
		--debugPrint(style)
		--
		--print("ref: ")
		--debugPrint(ref)
		--
		--print("localKey")
		--debugPrint(localKey)
		--
		--print("packed: ")
		--debugPrint(packed)

		-- create a node with not-yet-initialized list of children and return its id
		local cppProps = {style = style, props = packed}
		local result = callingRecipeCtx:makeNodeWithProps(recipeId, localKey, cppProps, nil, discardNodeIdentity)

		if ref then
			local refResult = callingRecipeCtx:makeNodeRef(result)
			if type(ref) == "table" then
				for __, v in ipairs(ref) do
					v:set(refResult)
				end
			else
				ref:set(refResult)
			end
		end


		if meta then
			local compParams = {}
			for k, v in pairs(meta) do
				if k ~= "class" and k ~= "localKey" and k ~= "discardNodeIdentity" then
					compParams[k] = v
				end
			end
			if next(compParams) ~= nil then
				compParams.item = result
				return builtin.WithComponentParams(compParams)
			end
		end

		return result
	end

	_react.originalRecipeFn[recipeId] = resultOriginal

	local result = function(...)
		local replacement = _react.recipeReplace[recipeId] or nil
		if replacement then
			return replacement(...)
		end
		return resultOriginal(...)
	end
	-- map back from function to Id for the rare cases where the Id is actually needed
	recipeFnToRecipeId[result] = recipeId
	recipeFnToRecipeName[result] = name

	return result
end

