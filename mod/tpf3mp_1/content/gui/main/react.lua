local function getPlugins(extensionPoint)
	if extensionPoint == nil or not _react.extensionPoints[extensionPoint.id] then
		return {}
	end

	local pluginIds = api.res.genericRep.getAllOfType("react-plugin " .. extensionPoint.id)
	local plugins = {}
	for __, pluginId in ipairs(pluginIds) do
		local genericRes = api.res.genericRep.get(pluginId)
		local desc = genericRes.data
		local recipeFn = util.useFn(desc.filePath)
		if not recipeFn then
			log.error("Recipe not found: " .. tostring(desc.filePath) .. " (for a plugin for extension point " .. tostring(extensionPoint.id) .. ")")
		end
		local conditionFn = desc.condition and util.useFn(desc.condition) or nil
		plugins[#plugins + 1] = {
			recipe = recipeFn,
			order = desc.order,
			condition = conditionFn,
		}
	end

	table.sort(plugins, function(l, r)
		return (l.order or 0) < (r.order or 0)
	end)
	return plugins
end


