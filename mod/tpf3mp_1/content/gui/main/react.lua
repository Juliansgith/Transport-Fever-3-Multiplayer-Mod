local function makePendingAndDoExecute()
	local result = {
		pending = {}
	}

	if tracy then
		result.doExecute = function()
			while #result.pending > 0 do
				local iterating = result.pending
				result.pending = {}

				for __, fnAndScope in ipairs(iterating) do
					tracy.ZoneBeginN(fnAndScope[2] or "Fn")
					fnAndScope[1]()
					tracy.ZoneEnd()
				end
			end
		end
	else
		result.doExecute = function()
			while #result.pending > 0 do
				local iterating = result.pending
				result.pending = {}

				for __, fnAndScope in ipairs(iterating) do
					fnAndScope[1]()
				end
			end
		end
	end

	return result
end

