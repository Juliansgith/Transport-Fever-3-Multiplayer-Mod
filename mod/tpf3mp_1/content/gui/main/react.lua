local function isStyleParam(x)
	return x and type(x) == "table" and x.is_react_style_info == true
end
local function isRefParam(x)
	return x and type(x) == "table" and x.is_react_ref_info == true
end

-- extract style special parameters (if present). They must be the 1st two
local function splitParams(a, b, ...)
	if (isStyleParam(a)) then
		if (isRefParam(b)) then
			return a.data, b.data, table.pack(...)
		else
			return a.data, nil, table.pack(b, ...)
		end
	elseif (isRefParam(a)) then
		if (isStyleParam(b)) then
			return b.data, a.data, table.pack(...)
		else
			return nil, a.data, table.pack(b, ...)
		end
	else
		return nil, nil, table.pack(a, b, ...)
	end
end

local function makeUserdata(paramsType, paramsMap)
	local class = api.gui.react.params.builtin[paramsType]
	if class == nil then
		local str = string_util.format("Could not find builtin class '{paramsType}', Available:\n{available}", {
			paramsType = toString(paramsType),
			available = toString(api.gui.react.params.builtin),
		})
		error(str)
	end
	if (class.new == nil) then
		local str = string_util.format("Could not find constructor for builtin class '{paramsType}', Available:\n{available}", {
			paramsType = toString(paramsType),
			available = toString(class),
		})
		error(str)
	end
	if paramsMap == nil then
		return class.new()
	end
	if type(paramsMap) == "userdata" then
		return class.new(paramsMap)
	end
	local userdata = class.new()
	local res, err = pcall(function()
		for key, value in pairs(paramsMap) do
			if key ~= "meta" then
				-- copy the attribute (this causes an error if the key doesn't exist!)
				userdata[key] = value
			end
		end
	end)
	if not res then
		for key, value in pairs(paramsMap) do
			if key ~= "meta" then
				-- copy the attribute (this causes an error if the key doesn't exist!)
				local res, err = pcall(function() -- !!
					userdata[key] = value
				end)
				if not res then
					local str = string_util.format("Could not assign value to userdata '{key}',\nuserdata = {data},\nvalue = {value}: {error}", {
						key = key,
						data = toString(userdata),
						value = toString(value),
						error = err
					})
					str = str .. "\n" .. debug.traceback()
					error(str)
				end
			end
		end
	end
	return userdata
end

