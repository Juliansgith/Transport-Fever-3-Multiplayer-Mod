local function fixIsEnabledBool(isEnabledFn)
	if not isEnabledFn then
		return nil
	end
	return function()
		local result = isEnabledFn()
		if type(result) == "boolean" then
			return result and api.gui.inputAction.InputActionState.Enabled or api.gui.inputAction.InputActionState.Inactive
		end
		return result
	end
end

local function makeDropContext(fns)
	local getAllItems = function()
		return api.gui.dnd.getAllTransferData()
	end
	local getItems = fns.filter and function()
		local result = {}
		local all = api.gui.dnd.getAllTransferData()
		for __, v in ipairs(all) do
			if (fns.filter(v.type, v.data)) then
				result[#result + 1] = v
			end
		end
		return result
	end or getAllItems
	local dropContext = {
		getItems = getItems,
		getAllItems = getAllItems,
		anyMatch = function()
			return next(getItems()) ~= nil
		end
	}
	return dropContext
end
local function makeDnDListener(fns)
	return function(event)
		if event.type == api.gui.dnd.Event.Type.DragStarted then
			if fns.grab then
				local grabbed, cursor = fns.grab()
				if not grabbed then
					return false
				end
				for __, item in ipairs(grabbed) do
					api.gui.dnd.addTransferData(event, item, item)
				end
				if not cursor then
					cursor = 1010 -- "Grab" in gui_react_util.tl
				end
				if cursor then
					api.gui.dnd.setCursor(cursor)
				end
				return true
			end
		elseif event.type == api.gui.dnd.Event.Type.Drop then
			if fns.drop then
				return fns.drop(makeDropContext(fns)) or false
			end
		elseif event.type == api.gui.dnd.Event.Type.DragEntered then
			if fns.enter then
				return fns.enter(makeDropContext(fns)) or false
			end
		elseif event.type == api.gui.dnd.Event.Type.DragExited then
			if fns.exit then
				return fns.exit(makeDropContext(fns)) or false
			end
		end
		return false
	end
end

