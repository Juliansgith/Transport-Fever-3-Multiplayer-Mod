local function GloballyReplaceRecipeBeforeInitInternal(recipeFn, replacementRecipeFn)
	if not _react.recipeReplacementAllowed then
		log.warning(string_util.format("ignored react.GloballyReplaceRecipeBeforeInitInternal() because recipe execution already started (tried to replace {recipeName} with {replacementName})", {
			recipeName = GetRecipeName(recipeFn),
			replacementName = replacementRecipeFn and GetRecipeName(replacementRecipeFn) or "nil",
		}))
		return
	end
	local recipeId = GetRecipeId(recipeFn)
	_react.recipeReplace[recipeId] = replacementRecipeFn
end

local function CallOriginalRecipe(possiblyReplaced, ...)
	local name = GetRecipeName(possiblyReplaced)
	if name and _react.builtin[name] then
		log.error(string_util.format("CallOriginalRecipe() is not allowed for builtins (tried for {recipeName})", {recipeName = name}))
		return nil
	end
	local recipeId = GetRecipeId(possiblyReplaced)
	return _react.originalRecipeFn[recipeId](...)
end

